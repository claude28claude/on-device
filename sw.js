/* ---- Install: save every file ---------------------------- */
self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      /* Added one at a time so a single missing file does not
         silently abandon the whole cache. Anything that fails is
         reported in the console rather than hidden. */
      const failures = [];
      await Promise.all(
        PRECACHE.map(async (url) => {
          try {
            const response = await fetch(url, { cache: "reload" });
            if (!response.ok) throw new Error(`HTTP ${response.status}`);
            await cache.put(url, response);
          } catch (err) {
            failures.push({ url, message: err && err.message ? err.message : String(err) });
          }
        })
      );
      if (failures.length) {
        console.error("[On Device] These files could not be saved for offline use:", failures);
      }
      /* Take over as soon as possible so the first visit is already
         offline-capable. */
      await self.skipWaiting();
    })()
  );
});

/* ---- Activate: drop older versions ----------------------- */
self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys();
      await Promise.all(
        names
          .filter((name) => name.startsWith("ondevice-") && name !== CACHE)
          .map((name) => caches.delete(name))
      );
      await self.clients.claim();
    })()
  );
});

/* ---- Fetch: our own files, from the cache first ---------- */
self.addEventListener("fetch", (event) => {
  const request = event.request;

  /* Only ever GET, and only ever this site. Anything else is left
     completely alone. */
  if (request.method !== "GET") return;

  let url;
  try {
    url = new URL(request.url);
  } catch (err) {
    return;
  }
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    (async () => {
      const cached = await caches.match(request, { ignoreSearch: true });
      if (cached) return cached;

      try {
        const response = await fetch(request);
        /* Save anything successful for next time, so a tool's large
           module is only ever downloaded once. */
        if (response && response.ok && response.type === "basic") {
          const cache = await caches.open(CACHE);
          cache.put(request, response.clone());
        }
        return response;
      } catch (err) {
        /* Offline and not cached. For a page request, show the
           homepage, which is cached, rather than a browser error. */
        if (request.mode === "navigate") {
          const fallback = await caches.match("./index.html");
          if (fallback) return fallback;
        }
        return new Response(
          "This part of On Device is not saved on your device yet, and there is no " +
          "connection to fetch it with. Reconnect once and it will be saved for good.",
          { status: 503, headers: { "Content-Type": "text/plain; charset=utf-8" } }
        );
      }
    })()
  );
});

/* ---- Let a page tell us to activate immediately ---------- */
self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "SKIP_WAITING") {
    self.skipWaiting();
  }
});
