/* ============================================================
   On Device - the offline helper (service worker)

   Its only job is to keep a copy of this site's own files on your
   device so the site works with the internet switched off.

   It never touches your files, and it will not talk to any
   address other than this site's own. Requests to anywhere else
   are passed straight through untouched - and the Content
   Security Policy in every page refuses them anyway.

   The list below is generated by scripts/build-sw.mjs. Do not
   edit it by hand.
   ============================================================ */

/* --- BUILD:VERSION --- */
